ALTER TABLE R_OUTPUT ADD COLUMN IF NOT EXISTS stage VARCHAR(16) NOT NULL DEFAULT 'PRE_APPLY'
  CHECK (stage IN ('PRE_APPLY','APPLIED','PUBLISHED','GRANTED','TRANSFERRED'));
ALTER TABLE R_OUTPUT ADD COLUMN IF NOT EXISTS annual_fee_due DATE;
ALTER TABLE R_OUTPUT ADD COLUMN IF NOT EXISTS agency_id BIGINT;

CREATE TABLE R_PATENT_FEE (
    id        BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    patent_id BIGINT NOT NULL REFERENCES R_OUTPUT(id),
    year      INT NOT NULL,
    amount    NUMERIC(18,2) NOT NULL DEFAULT 0,
    paid_at   DATE,
    status    VARCHAR(16) NOT NULL DEFAULT 'UNPAID' CHECK (status IN ('UNPAID','PAID','WAIVED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE R_AGENCY (
    id        BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    name      VARCHAR(256) NOT NULL,
    contact   VARCHAR(256),
    deleted   SMALLINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
